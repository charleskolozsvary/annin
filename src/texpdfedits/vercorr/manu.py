def get_annidx_to_line(latex_file: Path):
    with open(latex_file, 'r') as f:
        lines = f.readlines()
    annidx_to_line = {}
    found_anns = []
    line_start, line_end = None, None
    for line_no, line in enumerate(lines, start=1):
        ann_match = re.search('%% Annotation (?P<index>[0-9]+)', line)
        if ann_match is not None:
            found_anns.append(int(ann_match.group('index')))
            continue
        if found_anns:
            start_snippet_match = re.search(r'^%⭣ ⭣ ⭣', line)
            if start_snippet_match is not None:
                line_start = line_no + 1
                continue
        if line_start is not None:
            end_snippet_match = re.search(r'^%⭡ ⭡ ⭡', line)
            if end_snippet_match is not None:
                line_end = line_no - 1
        found_annin_lines = (
            line_start is not None and
            line_end is not None and
            found_anns
        )
        if found_annin_lines:
            if not line_end >= line_start:
                raise RuntimeError(
                    f"line_start > line_end: {line_start} > {line_end}"
                )
            line_middle = (line_start + line_end) // 2
            for annidx in found_anns:
                annidx_to_line[annidx] = line_middle
            found_anns = []
            line_start = None
            line_end = None
    return annidx_to_line

def get_isolated_edit_pixmap(
        man: Manuscript,
        edit: Edit,
        image_rectangle: pymupdf.Rect
) -> pymupdf.Pixmap:
    tmp_doc_obj = pymupdf.open(man.annots_pdf)
    tmp_page = tmp_doc_obj[edit.pageno]
    for ann in tmp_page.annots():
        if not (ann.xref == edit.xref or ann.xref == edit.related_xref):
            # for some reason tmp_page.delete_annot(ann) doesn't work
            tmp_doc_obj.xref_set_key(ann.xref, 'Rect', '[ 0 0 0 0 ]')
    r = edit.annot_rect
    circle_rect = pymupdf.Rect(
        r.x0 - ATTENTION_BOX_GROW,
        r.y0 - ATTENTION_BOX_GROW,
        r.x1 + ATTENTION_BOX_GROW,
        r.y1 + ATTENTION_BOX_GROW,
    )
    tmp_page.add_rect_annot(circle_rect)

    return tmp_page.get_pixmap(
        dpi=IMAGE_DPI,
        clip=image_rectangle,
        annots=SHOW_ANNS,
    )
    
def get_before_pixmap(man: Manuscript, edit: Edit) -> pymupdf.Pixmap:
    page = man.annots_pdf_doc[edit.pageno]
    page_width, page_height = page.rect.width, page.rect.height
    image_extend = man.ba_half_image_height
    
    im_x_start = IMAGE_X_START
    im_y_start = max(edit.annot_rect.y0 - image_extend, 0)
    im_x_end   = page_width
    im_y_end   = min(edit.annot_rect.y1 + image_extend, page_height)
    
    image_rectangle = pymupdf.Rect(
        im_x_start,
        im_y_start,
        im_x_end,
        im_y_end
    )
    pixmap = get_isolated_edit_pixmap(man, edit, image_rectangle)
    return pixmap

def choose_synctex_out(
        man: Manuscript,
        edit: Edit,
        synctex_outs: list[SynctexOut]
) -> SynctexOut:
    """
    If SyncTeX outputs have different *pages*
    we choose the first one that is greater than the
    maximum of the previous SyncTeX pages or, if there
    aren't any such cases, just the first output like usual
    """
    outs_before = man.get_synctex_outs_before(edit.xref)
    if not outs_before:
        return synctex_outs[0]
    min_page_thresh = max(ob.page for ob in outs_before)
    # heuristic: bias toward later pages if synctex_outs offer multiple
    filtered_outs = [
        sync_out for sync_out in synctex_outs
        if sync_out.page > min_page_thresh
    ]
    if not filtered_outs:
        return synctex_outs[0]
    else:
        return filtered_outs[0]

def acquire_synctex_out(man: Manuscript, edit: Edit):
    line = man.xref_to_line.get(edit.xref, None)
    if line is None:
        logger.warning(f"Annot with xref {edit.xref} was not written in {man.latex_file}")
        return
    synctex_result = sync.run_synctex_view(line, man.latex_file.absolute(), man.latex_pdf.absolute())
    try:
        synctex_outs = sync.parse_synctex_view(synctex_result)
    except RuntimeError as e:
        logger.warning(f"SyncTeX could not locate output of line {line} from {man.latex_file}: {e}")
        return

    chosen_out = choose_synctex_out(man, edit, synctex_outs)
    man.set_synctex_out(edit.xref, chosen_out)

def get_after_pixmap(man: Manuscript, edit: Edit) -> pymupdf.Pixmap | None:
    if edit.xref not in man.xref_to_synctex:
        return None
    line, chosen_out = man.xref_to_synctex[edit.xref]
    pageno, x, y = (
        chosen_out.page,
        chosen_out.x,
        chosen_out.y,
    )
    # ic(edit.xref, pageno, x, y)
    page = man.generated_pdf_doc[pageno]
    edit_rect_nudge = edit.annot_rect.height / 2
    image_extend = man.ba_half_image_height

    im_x_start = IMAGE_X_START
    im_y_start = max(0, y - image_extend - edit_rect_nudge)
    im_x_end   = page.cropbox.width
    im_y_end   = min(y + image_extend + edit_rect_nudge, page.cropbox.height)
    
    image_rectangle = pymupdf.Rect(
        im_x_start,
        im_y_start,
        im_x_end,
        im_y_end,
    )
    return page.get_pixmap(
        clip=image_rectangle,
        dpi=IMAGE_DPI,
    )
